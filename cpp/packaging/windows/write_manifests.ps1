<#
.SYNOPSIS
Writes winget + Scoop manifests for a released Syspeek version, reading
SHA256 hashes from the local release artifacts.
.DESCRIPTION
Run AFTER a release is published (the URLs point at the tag download).
winget manifests go to microsoft/winget-pkgs as PRs; the Scoop manifest
goes into a bucket repo. Both are staged under cpp/packaging/windows/
manifests/ for that submission.

.EXAMPLE
powershell -File cpp/packaging/windows/write_manifests.ps1 -Version 0.8.0
#>
param(
    [Parameter(Mandatory = $true)]
    [string] $Version
)

$ErrorActionPreference = "Stop"

$outRoot = Join-Path $PSScriptRoot "manifests/$Version"
New-Item -ItemType Directory -Force $outRoot | Out-Null

$packDir = Join-Path (Split-Path -Parent (Split-Path -Parent (Split-Path -Parent $PSScriptRoot))) "cpp/build/packaging"
$msi = Join-Path $packDir "Syspeek-$Version-windows.msi"
$zip = Join-Path $packDir "Syspeek-$Version-windows-portable.zip"
if (-not (Test-Path $msi)) { throw "missing $msi" }
if (-not (Test-Path $zip)) { throw "missing $zip" }
$msiSha = (Get-FileHash -Algorithm SHA256 $msi).Hash.ToLower()
$zipSha = (Get-FileHash -Algorithm SHA256 $zip).Hash.ToLower()
$base = "https://github.com/codeafridi/Syspeek/releases/download/v$Version"

# ---- winget (manifest v1.6, three files) ----
$pkgId = "Codeafridi.Syspeek"
$wingetVersion = @"
# generated by cpp/packaging/windows/write_manifests.ps1; submit to the
# microsoft/winget-pkgs fork-then-PR flow. Unsigned builds: note the
# SmartScreen first-run in docs/windows.md.
PackageIdentifier: $pkgId
PackageVersion: $Version
PackageName: Syspeek
Publisher: Syspeek project
PackageUrl: https://github.com/codeafridi/Syspeek
License: MIT
LicenseUrl: https://github.com/codeafridi/Syspeek/blob/main/LICENSE.txt
ShortDescription: Local system HUD (CPU, memory, network, processes, containers) overlay for Linux, macOS and Windows.
Moniker: syspeek
Tags:
- monitoring
- hud
- systems
- performance
ReleaseNotesUrl: https://github.com/codeafridi/Syspeek/releases/tag/v$Version
ManifestType: version
ManifestVersion: 1.6.0
"@
$wingetVersion | Out-File -Encoding utf8 (Join-Path $outRoot "$pkgId.yaml")

$wingetInstaller = @"
# Windows installer: WiX MSI (per-machine). Portable zip published next
# to it for Scoop/no-install users.
PackageIdentifier: $pkgId
PackageVersion: $Version
Installers:
- InstallerLocale: en-US
  Architecture: x64
  InstallerType: wix
  InstallerUrl: $base/Syspeek-$Version-windows.msi
  InstallerSha256: $MSISHA
  ProductCode: '{9C7C4470-8E27-4BDB-98C9-3774BF58B4F9}'
- InstallerLocale: en-US
  Architecture: x64
  InstallerType: zip
  NestedInstallerType: portable
  InstallerUrl: $base/Syspeek-$Version-windows-portable.zip
  InstallerSha256: $ZIPSHA
  NestedInstallerFiles:
  - RelativeFilePath: syspeek.exe
    PortableCommandAlias: syspeek
ManifestType: installer
ManifestVersion: 1.6.0
"@
# PowerShell unescapes %{ } etc. above; rebind via expressions.
$wingetInstaller = $wingetInstaller.
    Replace('$MSISHA', $msiSha).
    Replace('$ZIPSHA', $zipSha)
$wingetInstaller | Out-File -Encoding utf8 (Join-Path $outRoot "$pkgId.installer.yaml")

$wingetLocale = @"
PackageIdentifier: $pkgId
PackageVersion: $Version
PackageLocale: en-US
Publisher: Syspeek project
PackageName: Syspeek
License: MIT
ShortDescription: Local system HUD overlay (CPU/memory/network/processes/containers).
Description: |-
  Syspeek is a lightweight native-Qt overlay HUD (Datadog-style) for your
  own machine: per-process CPU and memory, network sockets and rates,
  disks, containers, kubernetes info, alerts, log pipeline and more,
  collected locally only.
ManifestType: defaultLocale
ManifestVersion: 1.6.0
"@
$wingetLocale | Out-File -Encoding utf8 (Join-Path $outRoot "$pkgId.locale.en-US.yaml")

# ---- Scoop ----
$scoop = [ordered]@{
    version    = $Version
    url_msi    = "$base/Syspeek-$Version-windows.msi"
    msi_hash   = $msiSha
    url_zip    = "$base/Syspeek-$Version-windows-portable.zip"
    zip_hash   = $zipSha
}
$scoopJson = @{
    homepage    = "https://github.com/codeafridi/Syspeek"
    description = "Local system HUD (CPU, memory, network, processes, containers) overlay."
    version     = $Version
    license     = "MIT"
    notes       = "Unsigned build: Windows SmartScreen may warn on first run. Unzip and run syspeek.exe directly (portable) or install the MSI."
    url         = "$base/Syspeek-$Version-windows-portable.zip"
    hash        = $zipSha
    bin         = "syspeek.exe"
    checkver    = "github"
    autoupdate  = @{
        url    = "https://github.com/codeafridi/Syspeek/releases/download/v`$version/Syspeek-`$version-windows-portable.zip"
        hash   = @{ url = "https://github.com/codeafridi/Syspeek/releases/download/v`$version/Syspeek-`$version-windows-portable.zip.sha256" }
    }
}
$scoopJson | ConvertTo-Json -Depth 4 |
    Out-File -Encoding utf8 (Join-Path $outRoot "syspeek-scoop.json")

Write-Host "manifests written to $outRoot (winget: submit to microsoft/winget-pkgs; scoop: copy to a bucket repo)"
